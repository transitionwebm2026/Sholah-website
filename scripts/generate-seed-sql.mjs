/**
 * Turns the default content in `src/lib/cms/seed.json` into `supabase/seed.sql`.
 * Usage: node scripts/generate-seed-sql.mjs   (npm run cms:seed-sql)
 *
 * Every insert uses ON CONFLICT DO NOTHING with stable ids, so running seed.sql again never
 * duplicates rows or overwrites anything edited in the dashboard.
 */
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const seed = JSON.parse(await readFile(path.join(ROOT, 'src/lib/cms/seed.json'), 'utf8'));

/** Primary key per table (conflict target). Order matters: parents before children. */
const TABLES = [
  ['site_settings', 'id'],
  ['doctors_profile', 'id'],
  ['hero_sections', 'page'],
  ['page_sections', 'key'],
  ['surgeries_services', 'id'],
  ['surgery_procedures', 'id'],
  ['articles', 'id'],
  ['videos_gallery', 'id'],
  ['patient_reviews', 'id'],
  ['faqs', 'id']
];

/**
 * Dashboard admins. The Auth users themselves are created in Supabase (Authentication → Users);
 * this only grants them admin rights. The repository is public, so only a placeholder lives
 * here: replace it with the real admin email in the SQL Editor before running seed.sql.
 */
const ADMIN_EMAILS = ['admin@example.com'];

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

function literal(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'object') return `${quote(JSON.stringify(value))}::jsonb`;
  return quote(value);
}

const parts = [
  '-- Generated by scripts/generate-seed-sql.mjs from src/lib/cms/seed.json — do not edit by hand.',
  '-- Run once in Supabase → SQL Editor, after schema.sql. Safe to re-run: existing rows are kept.',
  '',
  'begin;',
  ''
];

for (const [table, key] of TABLES) {
  const rows = [seed[table]].flat();
  if (!rows.length) continue;
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((c) => literal(row[c])).join(', ')})`);
  parts.push(
    `-- ${table} (${rows.length})`,
    `insert into public.${table} (${columns.join(', ')}) values`,
    `${values.join(',\n')}`,
    `on conflict (${key}) do nothing;`,
    ''
  );
}

parts.push(
  '-- admins (users must already exist in Authentication → Users)',
  '-- Replace the placeholder email below with the dashboard admin\'s email before running.',
  'insert into public.admin_users (user_id)',
  `select id from auth.users where lower(email) in (${ADMIN_EMAILS.map((e) => quote(e.toLowerCase())).join(', ')})`,
  'on conflict (user_id) do nothing;',
  '',
  'commit;',
  ''
);

const out = path.join(ROOT, 'supabase/seed.sql');
await writeFile(out, parts.join('\n'));
console.log(`✓ ${path.relative(ROOT, out)} written`);
